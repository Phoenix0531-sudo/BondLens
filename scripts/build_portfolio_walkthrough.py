#!/usr/bin/env python3
"""Build a silent, 60-second visual tour from authentic portfolio-case screenshots.

This is a screenshot-based walkthrough, not a real-time interaction recording.
It uses the six captures generated by scripts/capture_portfolio_case.mjs.
Requires FFmpeg on PATH. Does not access the network or launch the application.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCREENS = ROOT / "docs" / "portfolio_case" / "screenshots"
OUTPUT = ROOT / "docs" / "portfolio_case" / "walkthrough.mp4"
SCENES = [
    ("01-market.png", 10),
    ("02-screen.png", 10),
    ("03-bond.png", 10),
    ("04-agent.png", 10),
    ("06-evidence-pack.png", 10),
    ("05-history.png", 10),
]


def main() -> None:
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        raise SystemExit("FFmpeg is required; install it or skip the optional video.")
    missing = [name for name, _ in SCENES if not (SCREENS / name).is_file()]
    if missing:
        raise SystemExit(f"Capture screenshots first: {', '.join(missing)}")

    args = [ffmpeg, "-hide_banner", "-loglevel", "error", "-y"]
    parts = []
    streams = []
    for index, (name, seconds) in enumerate(SCENES):
        args += ["-loop", "1", "-framerate", "12", "-t", str(seconds), "-i", str(SCREENS / name)]
        # Each frame comes from the running local app or the actual generated pack.
        parts.append(
            f"[{index}:v]scale=1440:900:force_original_aspect_ratio=decrease,"
            f"pad=1440:900:(ow-iw)/2:(oh-ih)/2:color=0xf8f8f8,"
            f"fps=12,format=yuv420p,"
            f"fade=t=in:st=0:d=0.35,fade=t=out:st={seconds - 0.35}:d=0.35[v{index}]"
        )
        streams.append(f"[v{index}]")
    parts.append("".join(streams) + f"concat=n={len(SCENES)}:v=1:a=0[out]")
    args += [
        "-filter_complex", ";".join(parts),
        "-map", "[out]",
        "-c:v", "libx264", "-preset", "veryfast", "-crf", "25",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart",
        "-an", str(OUTPUT),
    ]
    subprocess.run(args, check=True)
    print(f"Wrote {OUTPUT}, bytes={OUTPUT.stat().st_size}, duration=60s")


if __name__ == "__main__":
    main()
